BODY_BLOCK_TERMS: tuple[str, ...] = TITLE_BLOCK_TERMS + (
    "记者获悉", "从有关部门", "相关负责人表示", "通报称", "会议指出",
    "会议强调", "会议决定", "批示", "贺信", "致电", "调研", "督查",
    "印发", "整改", "事故", "死亡", "伤亡", "官方通报",
)
BODY_BLOCK_MIN_HITS = 3

# 命中这些「官方体裁」时阈值降到 1 —— 只要出现就是通稿
BODY_HARD_TERMS: tuple[str, ...] = (
    "记者获悉", "从有关部门", "相关负责人表示", "通报称", "会议指出",
    "会议强调", "批示", "贺信",
)


def _host(url: str) -> str:
    try:
        host = (urlparse(url or "").hostname or "").lower()
    except ValueError:
        return ""
    return host


def is_official_url(url: str) -> bool:
    """链接是否落在官方 / 政府域名（含子域）。"""
    host = _host(url)
    if not host:
        return False
    return any(host == d or host.endswith("." + d) for d in OFFICIAL_DOMAINS)


def blocked_reason(*, title: str, body: str = "", url: str = "") -> str:
    """返回丢弃原因；空串表示通过。"""
    if is_official_url(url):
        return "官方源域名"
    t = title or ""
    for term in TITLE_BLOCK_TERMS:
        if term in t:
            return f"标题含官方/时政词「{term}」"
    b = body or ""
    if b:
        for term in BODY_HARD_TERMS:
            if term in b:
                return f"正文是官方通稿（「{term}」）"
        hits = [term for term in BODY_BLOCK_TERMS if term in b]
        if len(hits) >= BODY_BLOCK_MIN_HITS:
            return "正文时政密度过高（" + "、".join(hits[:3]) + "）"
    return ""


def passes(**kwargs: str) -> bool:
    return not blocked_reason(**kwargs)
